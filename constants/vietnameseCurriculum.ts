export function getVietnameseWeek(weekNumber: number): WeekTopicSeed | undefined {
  return VIETNAMESE_WEEKS.find((week) => week.weekNumber === weekNumber);
}

export function getVietnameseWeekQuestions(weekNumber: number): Question[] {
  return getVietnameseWeek(weekNumber)?.questions ?? [];
}

/** Toàn bộ câu hỏi Tiếng Việt của cả lộ trình */
export const VIETNAMESE_QUESTIONS: Question[] = VIETNAMESE_WEEKS.flatMap(
  (week) => week.questions,
);
